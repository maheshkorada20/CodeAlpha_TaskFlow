const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    recipient: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },
    sender: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
    },
    type: {
      type: String,
      enum: [
        'INVITATION',
        'MEMBER_JOINED',
        'MEMBER_REMOVED',
        'ROLE_CHANGED',
        'TASK_ASSIGNED',
        'TASK_REASSIGNED',
        'TASK_STATUS_CHANGED',
        'TASK_SUBMITTED',
        'TASK_APPROVED',
        'TASK_REJECTED',
        'COMMENT_ADDED',
        'MENTION',
        'FILE_UPLOADED',
        'DEADLINE_APPROACHING',
      ],
      required: true,
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    project: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Project',
    },
    task: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Task',
    },
    isRead: {
      type: Boolean,
      default: false,
      index: true,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('Notification', notificationSchema);
